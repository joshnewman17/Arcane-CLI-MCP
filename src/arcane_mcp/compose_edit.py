"""Read and replace a project's compose file without exposing the MCP container's filesystem.

``arcane_run`` rejects every local-file flag (``projects update -f <path>`` would let a caller
upload any file inside this container, including the CLI config that holds the API key). This
module is the narrow alternative: the caller supplies compose *content*, the server writes it to a
private temp file of its own and runs ``projects update -f`` on exactly that file.

- Reads return the compose file only. The project's ``.env`` is never returned or written here:
  it holds secrets and stays in the Arcane UI.
- Writes need ``confirm=true``. Without it the result is ``needs_confirmation`` with a diff
  against the current file. They're blocked in read-only mode.
- Content is validated as a YAML mapping with ``services`` before anything is sent.
- The project is not redeployed: that stays a separate, visible step.

``create`` makes a new project the same way (``projects create -f <compose> --env-file <env>``). Its
``.env`` is generated by the server from the compose file's ``${VAR}`` references: non-secret values
come from the caller or the compose defaults, and anything that looks like a credential is the
placeholder ``CHANGE_ME``. The user fills in those values in the Arcane UI; ``read`` reports which placeholders are still unfilled (names only).
"""

from __future__ import annotations

import difflib
import hashlib
import os
import re
import shutil
import tempfile
import time
from pathlib import Path
from typing import Any

import yaml

from .api import ApiClient
from .audit import REDACTED, AuditLog, Redactor
from .cli import CliRunner, parse_json, tail

MAX_COMPOSE_BYTES = 256 * 1024
MAX_DIFF_CHARS = 12000
MAX_HINT_CHARS = 200
PLACEHOLDER = "CHANGE_ME"
_PROJECT = re.compile(r"^[A-Za-z0-9][A-Za-z0-9_.-]{0,127}$")
_ENV_KEY = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")
# ${VAR}, ${VAR:-default}, ${VAR-default}, ${VAR:?msg}, ${VAR?msg}; `$${...}` is an escaped literal.
_VAR_REF = re.compile(r"(?<!\$)\$\{([A-Za-z_][A-Za-z0-9_]*)(?:(:?-)([^}]*)|:?\?[^}]*)?\}")
_ENV_LINE = re.compile(r"^\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*?)\s*$")


# Variable names that hold credentials. These are always left as CHANGE_ME for the user to fill in,
# whatever the compose default or the caller says.
_SECRET_NAME = re.compile(
    r"(?i)(pass(word|wd|phrase)?|pwd|secret|token|api_?key|access_?key|private_?key|^key$|_key$|credential|"
    r"auth|salt|hash|cookie|session|license|dsn|webhook)"
)
_VALUE_CHARS = re.compile(r"^[^\r\n\x00]*$")


def is_secret_name(name: str) -> bool:
    return bool(_SECRET_NAME.search(name))


def _check_map(arg: str, mapping: Any) -> dict[str, str]:
    if mapping is None:
        return {}
    if not isinstance(mapping, dict):
        raise ValueError(f"{arg} must be an object of VAR names to strings")  # noqa: TRY004
    for key, value in mapping.items():
        if not isinstance(key, str) or not _ENV_KEY.match(key):
            raise ValueError(f"{arg} key {key!r} is not a valid variable name")
        if not isinstance(value, str) or len(value) > MAX_HINT_CHARS or not _VALUE_CHARS.match(value):
            raise ValueError(f"{arg}[{key!r}] must be a single line of at most {MAX_HINT_CHARS} characters")
        if REDACTED in value:
            raise ValueError(f"{arg}[{key!r}] contains {REDACTED!r}")
    return mapping


def env_template(compose: str, hints: dict[str, str] | None = None, values: dict[str, str] | None = None,
                 redactor: Redactor | None = None) -> tuple[str, list[str]]:
    """Build a .env for ``compose``.

    Each variable gets, in order: the caller's non-secret value from ``values``, the compose default,
    or ``CHANGE_ME``. Variables whose name looks like a credential are always ``CHANGE_ME``, and a
    ``values`` entry for one (or one whose value looks like a credential) is refused, so secrets only
    ever reach the .env through the Arcane UI. ``hints`` ({VAR: description}) add a comment above a
    variable. Keys in either map that the compose doesn't reference are added too.
    Returns (env text, placeholder names).
    """
    hints = _check_map("env_hints", hints)
    values = _check_map("env_values", values)
    for key, value in values.items():
        if is_secret_name(key):
            raise ValueError(f"env_values[{key!r}] looks like a secret: leave it out so the user enters it in "
                             "the Arcane UI (it will be CHANGE_ME in the .env)")
        if redactor is not None and redactor.text(f"{key}={value}") != f"{key}={value}":
            raise ValueError(f"env_values[{key!r}] looks like a credential: leave it out so the user enters "
                             "it in the Arcane UI")

    found: dict[str, str | None] = {}
    for m in _VAR_REF.finditer(compose):
        name, op, default = m.group(1), m.group(2), m.group(3)
        if found.get(name) is None:
            found[name] = default if op and default and "\n" not in default else None
    for key in [*hints, *values]:
        found.setdefault(key, None)

    lines = [f"# Generated by arcane-cli-mcp. Replace every {PLACEHOLDER} in the Arcane UI before deploying."]
    placeholders = []
    for name, default in found.items():
        value = None if is_secret_name(name) else values.get(name, default)
        if hints.get(name):
            lines.append(f"# {hints[name]}")
        if value is None:
            placeholders.append(name)
            value = PLACEHOLDER
        lines.append(f"{name}={value}")
    return "\n".join(lines) + "\n", placeholders


def unfilled(env: str) -> list[str]:
    """Names of variables in a .env whose value is still the placeholder."""
    out = []
    for line in env.splitlines():
        m = _ENV_LINE.match(line)
        if m and m.group(2).strip("'\"") == PLACEHOLDER:
            out.append(m.group(1))
    return out


class ComposeEditor:
    def __init__(self, runner: CliRunner, api: ApiClient, redactor: Redactor, audit: AuditLog) -> None:
        self.runner = runner
        self.api = api
        self.redactor = redactor
        self.audit = audit
        self.settings = runner.settings

    # -- helpers -------------------------------------------------------------------------------

    def _resolve(self, project: str, env_id: str | None) -> tuple[str, str]:
        if not isinstance(project, str) or not _PROJECT.match(project):
            raise ValueError("project must be a project name or id (letters, digits, '.', '_', '-')")
        return project, self.runner.resolve_env(env_id)

    def _project_id(self, project: str, env: str) -> str:
        code, stdout, stderr, _ = self.runner.exec(
            self.runner.base_argv() + ["projects", "get", project, "--env", env, "--json"],
            self.settings.default_timeout_s,
        )
        parsed, data = parse_json(stdout)
        if code != 0 or not parsed or not isinstance(data, dict):
            raise LookupError(tail(self.redactor.text(stderr), 300) or f"project {project!r} not found")
        data = data.get("data", data)
        if not isinstance(data, dict) or not data.get("id"):
            raise LookupError(f"project {project!r} not found")
        return str(data["id"])

    def _current(self, project: str, env: str) -> dict[str, Any]:
        project_id = self._project_id(project, env)
        r = self.api.get(f"/api/environments/{env}/projects/{project_id}/compose")
        if not r.get("ok"):
            raise LookupError(r.get("error") or f"Arcane returned HTTP {r.get('status')}")
        data = r.get("data") or {}
        data = data.get("data", data) if isinstance(data, dict) else {}
        compose = data.get("composeContent") or ""
        try:
            doc = yaml.safe_load(compose)
            services = list(doc["services"]) if isinstance(doc, dict) and isinstance(doc.get("services"), dict) else []
        except yaml.YAMLError:
            services = []
        return {
            "project_id": project_id,
            "compose_file": data.get("composeFileName"),
            # Already passed through the redactor by ApiClient; envContent is withheld there too.
            "compose": compose,
            "services": services,
        }

    def _redact_env(self, env: str) -> str:
        """Redact a generated .env for display, leaving placeholder lines readable."""
        return "\n".join(line if unfilled(line) else self.redactor.text(line) for line in env.split("\n"))

    def _env_unfilled(self, env: str, project_id: str) -> list[str] | None:
        """Placeholder names still in the project's .env, or None if it can't be checked.

        Reads the raw .env server-side; only variable names leave this method, never values.
        """
        try:
            data = self.api.get_private(f"/api/environments/{env}/projects/{project_id}/compose")
            data = data.get("data", data) if isinstance(data, dict) else {}
            content = data.get("envContent") if isinstance(data, dict) else None
        except Exception:  # noqa: BLE001 - best effort; never surface raw content in errors
            return None
        return unfilled(content) if isinstance(content, str) else []

    @staticmethod
    def validate(compose: Any) -> None:
        if not isinstance(compose, str) or not compose.strip():
            raise ValueError("compose must be the full compose file as a non-empty string")
        if len(compose.encode()) > MAX_COMPOSE_BYTES:
            raise ValueError(f"compose is larger than {MAX_COMPOSE_BYTES // 1024} KiB")
        if "\x00" in compose:
            raise ValueError("compose may not contain NUL bytes")
        if REDACTED in compose:
            raise ValueError(
                f"compose contains {REDACTED!r}: a value was hidden when the file was read and can't be "
                "restored through MCP. Move that secret into the project's .env (in the Arcane UI) and "
                "reference it as ${VAR}."
            )
        try:
            doc = yaml.safe_load(compose)
        except yaml.YAMLError as exc:
            raise ValueError(f"compose is not valid YAML: {str(exc).splitlines()[0]}") from exc
        if not isinstance(doc, dict) or not isinstance(doc.get("services"), dict) or not doc["services"]:
            raise ValueError("compose must be a mapping with a non-empty 'services' section")

    # -- tool entry points -----------------------------------------------------------------------

    def read(self, project: str, env_id: str | None = None) -> dict[str, Any]:
        try:
            project, env = self._resolve(project, env_id)
            current = self._current(project, env)
        except (ValueError, LookupError) as exc:
            self.audit.record(tool="arcane_project_compose", action="read", project=project, outcome="error",
                              reason=str(exc))
            return {"ok": False, "error": str(exc)}
        env_unfilled = self._env_unfilled(env, current["project_id"])
        self.audit.record(tool="arcane_project_compose", action="read", project=project, env_id=env,
                          outcome="ok", bytes=len(current["compose"]))
        result = {"ok": True, "project": project, "env_id": env, **current,
                  "note": "The project's .env is not shown; it holds secrets and is edited in the Arcane UI."}
        if env_unfilled is not None:
            result["env_unfilled"] = env_unfilled
            if env_unfilled:
                result["note"] += (f" These .env variables still hold the {PLACEHOLDER} placeholder: ask the user "
                                   "to fill them in the Arcane UI before deploying.")
        return result

    def write(self, project: str, compose: str, env_id: str | None = None,
              confirm: bool = False) -> dict[str, Any]:
        started = time.monotonic()
        audit: dict[str, Any] = {"tool": "arcane_project_compose", "action": "write", "project": project,
                                 "env_id": env_id, "confirm": confirm}
        if self.settings.readonly:
            self.audit.record(**audit, outcome="blocked", reason="read-only mode")
            return {"ok": False, "blocked": True,
                    "error": "Editing compose files is not permitted: the server is in read-only mode."}
        try:
            project, env = self._resolve(project, env_id)
            audit["env_id"] = env
            self.validate(compose)
            current = self._current(project, env)
        except (ValueError, LookupError) as exc:
            self.audit.record(**audit, outcome="rejected", reason=str(exc))
            return {"ok": False, "error": str(exc)}

        digest = hashlib.sha256(compose.encode()).hexdigest()[:16]
        audit.update(sha256=digest, bytes=len(compose.encode()))
        diff = "\n".join(difflib.unified_diff(
            current["compose"].splitlines(), compose.splitlines(),
            f"{project}/{current['compose_file'] or 'compose.yaml'} (current)", f"{project} (new)", lineterm="", n=2,
        ))
        if not diff:
            self.audit.record(**audit, outcome="unchanged")
            return {"ok": True, "unchanged": True, "message": "The compose file already has this content."}
        if len(diff) > MAX_DIFF_CHARS:
            diff = diff[:MAX_DIFF_CHARS] + f"\n… diff truncated at {MAX_DIFF_CHARS} characters"

        if not confirm:
            self.audit.record(**audit, outcome="needs_confirmation")
            return {"ok": False, "needs_confirmation": True, "project": project, "env_id": env, "diff": diff,
                    "message": "Nothing was changed. Show the user this diff and ask them to approve it, then call "
                               "arcane_project_compose again with the same compose and confirm=true. The project "
                               "is not redeployed by this tool."}

        tmpdir = Path(tempfile.mkdtemp(prefix="compose-", dir=self.settings.state_dir))
        try:
            os.chmod(tmpdir, 0o700)
            path = tmpdir / "compose.yaml"
            fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
            with os.fdopen(fd, "w", encoding="utf-8") as fh:
                fh.write(compose)
            argv = self.runner.base_argv() + ["projects", "update", project, "-f", str(path),
                                              "--env", env, "--json", "--yes"]
            code, stdout, stderr, timed_out = self.runner.exec(argv, self.settings.default_timeout_s)
        finally:
            shutil.rmtree(tmpdir, ignore_errors=True)

        ok = code == 0 and not timed_out
        self.audit.record(**audit, outcome="ok" if ok else "error", exit_code=code,
                          duration_ms=int((time.monotonic() - started) * 1000))
        result: dict[str, Any] = {"ok": ok, "exit_code": code, "project": project, "env_id": env, "diff": diff}
        parsed, data = parse_json(stdout)
        if parsed and isinstance(data, dict):
            data = self.redactor.obj(data.get("data", data))
            result["project_state"] = {k: data.get(k) for k in ("name", "status", "serviceCount", "updatedAt")}
        if stderr.strip():
            result["stderr_tail"] = tail(self.redactor.text(stderr))
        if ok:
            result["message"] = ("Compose file updated. Running containers are unchanged until the project is "
                                 "redeployed: ask the user, then run arcane_run ['projects', 'redeploy', "
                                 f"'{project}'].")
        return result

    def create(self, project: str, compose: str, env_id: str | None = None,
               env_hints: dict[str, str] | None = None, env_values: dict[str, str] | None = None,
               confirm: bool = False) -> dict[str, Any]:
        started = time.monotonic()
        audit: dict[str, Any] = {"tool": "arcane_project_create", "action": "create", "project": project,
                                 "env_id": env_id, "confirm": confirm}
        if self.settings.readonly:
            self.audit.record(**audit, outcome="blocked", reason="read-only mode")
            return {"ok": False, "blocked": True,
                    "error": "Creating projects is not permitted: the server is in read-only mode."}
        try:
            project, env = self._resolve(project, env_id)
            audit["env_id"] = env
            self.validate(compose)
            env_text, placeholders = env_template(compose, env_hints, env_values, self.redactor)
        except ValueError as exc:
            self.audit.record(**audit, outcome="rejected", reason=str(exc))
            return {"ok": False, "error": str(exc)}
        try:
            self._project_id(project, env)
        except LookupError:
            pass
        else:
            self.audit.record(**audit, outcome="rejected", reason="project exists")
            return {"ok": False, "error": f"Project {project!r} already exists. Use arcane_project_compose to "
                                          "change its compose file."}

        doc = yaml.safe_load(compose)
        services = list(doc["services"])
        digest = hashlib.sha256(compose.encode()).hexdigest()[:16]
        audit.update(sha256=digest, bytes=len(compose.encode()), placeholders=placeholders)
        preview = {"project": project, "env_id": env, "services": services,
                   "env_file": self._redact_env(env_text), "placeholders": placeholders}

        if not confirm:
            self.audit.record(**audit, outcome="needs_confirmation")
            return {"ok": False, "needs_confirmation": True, **preview,
                    "message": "Nothing was created. Show the user the project name, services and the generated "
                               ".env, and ask them to approve. Then call arcane_project_create again with the "
                               "same arguments and confirm=true. The project is not deployed by this tool."}

        tmpdir = Path(tempfile.mkdtemp(prefix="compose-", dir=self.settings.state_dir))
        try:
            os.chmod(tmpdir, 0o700)
            paths = {}
            for name, content in (("compose.yaml", compose), (".env", env_text)):
                paths[name] = tmpdir / name
                fd = os.open(paths[name], os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
                with os.fdopen(fd, "w", encoding="utf-8") as fh:
                    fh.write(content)
            argv = self.runner.base_argv() + ["projects", "create", "--name", project,
                                              "-f", str(paths["compose.yaml"]), "--env-file", str(paths[".env"]),
                                              "--env", env, "--json", "--yes"]
            code, stdout, stderr, timed_out = self.runner.exec(argv, self.settings.default_timeout_s)
        finally:
            shutil.rmtree(tmpdir, ignore_errors=True)

        ok = code == 0 and not timed_out
        self.audit.record(**audit, outcome="ok" if ok else "error", exit_code=code,
                          duration_ms=int((time.monotonic() - started) * 1000))
        result: dict[str, Any] = {"ok": ok, "exit_code": code, **preview}
        parsed, data = parse_json(stdout)
        if parsed and isinstance(data, dict):
            data = self.redactor.obj(data.get("data", data))
            result["project_state"] = {k: data.get(k) for k in ("id", "name", "status", "serviceCount")}
        if stderr.strip():
            result["stderr_tail"] = tail(self.redactor.text(stderr))
        if ok:
            if placeholders:
                result["message"] = (
                    f"Project created but NOT deployed. Ask the user to open Arcane -> Projects -> {project} -> "
                    f".env and replace {PLACEHOLDER} for: {', '.join(placeholders)}. Then check with "
                    "arcane_project_compose (env_unfilled must be empty) and, with the user's OK, run "
                    f"arcane_run ['projects', 'up', '{project}'].")
            else:
                result["message"] = (f"Project created but NOT deployed. With the user's OK, run "
                                     f"arcane_run ['projects', 'up', '{project}'].")
        return result
